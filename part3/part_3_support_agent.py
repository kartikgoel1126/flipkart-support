def evaluate_retrieval():
    rows = []

    for item in evaluation_queries:

        query = item["query"]
        relevant_docs = set(item["relevant_doc_ids"])

        results = retrieve_policy(query, k=3)

        retrieved_docs = []

        for result in results:
            doc_id = result["chunk"]["doc_id"]

            if doc_id not in retrieved_docs:
                retrieved_docs.append(doc_id)

        top3_docs = retrieved_docs[:3]

        relevant_retrieved = len(
            set(top3_docs) & relevant_docs
        )

        precision = relevant_retrieved / 3

        recall = (
            relevant_retrieved / len(relevant_docs)
            if relevant_docs
            else 0
        )

        rows.append({
            "query": query,
            "relevant_documents": list(relevant_docs),
            "retrieved_top3": top3_docs,
            "relevant_retrieved": relevant_retrieved,
            "precision_at_3": precision,
            "recall_at_3": recall
        })

    return rows



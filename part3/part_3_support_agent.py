def groundedness_guard(state):

    if state.get("intent") != "policy":
        return state

    results = state.get(
        "retrieved_chunks",
        []
    )

    if not results:

        state["answer"] = (
            "I could not find a sufficiently "
            "relevant policy in the knowledge base."
        )

        state["source"] = "policy_kb"

        state["confidence"] = 0.0

        return state

    similarity = results[0].get(
        "score", # Changed from 'similarity' to 'score'
        0.0
    )

    if similarity < MIN_POLICY_SIMILARITY:

        state["answer"] = (
            "I could not find a sufficiently "
            "relevant policy in the knowledge base."
        )

        state["source"] = "policy_kb"

        state["confidence"] = float(
            similarity
        )

        return state

    return state


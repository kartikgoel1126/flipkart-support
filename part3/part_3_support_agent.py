def check_return_risk(order_features: dict) -> dict:

    df = pd.DataFrame([order_features])

    probability = float(
        model.predict_proba(df)[0][1]
    )

    if probability < T_RF:
        risk = "Low"

    elif probability >= T_RF + 0.15:
        risk = "High"

    else:
        risk = "Medium"

    return {
        "return_probability": round(probability, 4),
        "risk_bucket": risk,
        "threshold_t_rf": T_RF
    }
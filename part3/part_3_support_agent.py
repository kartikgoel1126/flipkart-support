def intent_node(state):

    text = state["user_input"].lower()

    # RETURN RISK MUST BE CHECKED FIRST
    if any(phrase in text for phrase in [
        "return risk",
        "risk of return",
        "return probability",
        "likely to return",
        "probability of return",
        "risk"
    ]):
        intent = "return_risk"

    # IMAGE / PRODUCT CLASSIFICATION
    elif any(word in text for word in [
        "image",
        "photo",
        "picture",
        "classify",
        "classification"
    ]) and any(word in text for word in [
        "product",
        "category",
        "image",
        "photo",
        "picture"
    ]):
        intent = "product_category"

    # POLICY QUESTIONS
    elif any(word in text for word in [
        "return",
        "refund",
        "delivery",
        "policy",
        "pickup",
        "eligible"
    ]):
        intent = "policy"

    else:
        intent = "unknown"

    state["intent"] = intent

    return state


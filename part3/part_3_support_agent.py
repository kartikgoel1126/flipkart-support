class AgentState(TypedDict, total=False):
    user_input: str
    intent: str
    retrieved_chunks: list
    tool_result: dict
    answer: str
    source: str
    confidence: float
    order_features: dict
    image_path: str
    last_order_features: dict

def intent_node(state):
    text = state["user_input"].lower()
    if any(phrase in text for phrase in [
        "return risk", "risk of return", "return probability",
        "likely to return", "probability of return", "risk"
    ]):
        intent = "return_risk"
    elif any(word in text for word in [
        "image", "photo", "picture", "classify", "classification"
    ]) and any(word in text for word in [
        "product", "category", "image", "photo", "picture"
    ]):
        intent = "product_category"
    elif any(word in text for word in [
        "return", "refund", "delivery", "policy", "pickup", "eligible"
    ]):
        intent = "policy"
    else:
        intent = "unknown"
    state["intent"] = intent
    return state

